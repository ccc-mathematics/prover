const C = require('../src/cube.js'); let fail = 0;
const ok = (c, m) => { console.log((c ? 'PASS  ' : 'FAIL  ') + m); if (!c) fail++; };
for (const e of C.examples) ok(C.runScript(e.src).ok === !e.name.includes('錯誤'), e.name);
const t = s => C.runScript(s);
ok(!t('system λP\ndef id : forall (A : Prop), A -> A := fun (A : Prop) (x : A) => x').ok, 'λP 沒有多型,拒絕 ∀(A:Prop)');
ok(!t('system λ2\ndef And (A B : Prop) : Prop := forall (C : Prop), (A -> B -> C) -> C').ok, 'λ2 沒有型別運算子,拒絕 Prop→Prop→Prop');
ok(!t('system λ2\ndef id : forall (A : Prop), A -> A := fun (A : Prop) (x : A) => x\ncheck id id').ok, '型別不吻合的應用被拒絕');
ok(!t('axiom P : Prop\ntheorem t : P := by\n  intro h').ok, '目標不是 Π 時 intro 失敗');
ok(t('axiom P : Prop\ntheorem t : P := by\n  sorry').cmds[1].status === 'sorry', 'sorry 會被標記');
ok(t('axiom P : Prop\ntheorem t : P -> P := by\n  intro h').cmds[1].status === 'open', '未完成的證明回報 open');
ok(!t('check Type').ok, 'Type 沒有型別');
const run = s => C.runScript(s);
ok(run('system λ2\nimport eq').cmds[1].status === 'error', 'λ2 無法載入 eq 套件(需要 λC)');
ok(run('system λC\nimport eq\nimport nat\ntheorem t (n : Nat) : Eq Nat (add n zero) n := by\n  rfl').ok, 'rfl:ι 化簡證明 n + 0 = n');
ok(run('system λC\nimport eq\ntheorem t (A : Prop) (a b : A) (h : Eq A a b) : Eq A b a := by\n  rw h\n  rfl').ok, 'rw 之後 rfl');
ok(run('system λC\nimport eq\ntheorem t (A : Prop) (a b c : A) (h : Eq A a b) : Eq A c c := by\n  rw h').cmds[2].status === 'error', 'rw 找不到目標中的項會失敗');
ok(run('system λC\nimport eq\nimport nat\ntheorem t (n : Nat) : Eq Nat (add n n) n := by\n  induction n\n  rfl\n  sorry').cmds[3].status === 'sorry', 'induction 產生兩個目標');
ok(run('system λω\ndef Ex (A : Prop) (P : A -> Prop) : Prop := forall (C : Prop), (forall (x : A), P x -> C) -> C\ntheorem t (A : Prop) (P : A -> Prop) (h : Ex A P) : Ex A P := by\n  intro C f\n  apply f').cmds[1].status === 'error', 'apply 推不出的參數會明確報錯');
process.exit(fail ? 1 : 0);
